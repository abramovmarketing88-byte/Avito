def parse_titles(export_path: Path) -> list[str]:
    text = export_path.read_text(encoding="utf-8")
    found = re.findall(r"\u041e\u0431\u044a\u044f\u0432\u043b\u0435\u043d\u0438\u0435: \u00ab([^\u00bb]+)\u00bb", text)
    titles = list(dict.fromkeys(found))
    return titles if titles else DEFAULT_TITLES


def build_addresses() -> list[str]:
    addrs: list[str] = []
    for loc in KAZAN_LOCS[:50]:
        addrs.append(f"{RT}, {KAZAN}, {loc}")
    for loc in CHELNY_LOCS[:20]:
        addrs.append(f"{RT}, {CHELNY}, {loc}")
    for city in OTHER_CITIES[:130]:
        addrs.append(f"{RT}, {city}")
    return addrs



def pick_title(titles: list[str], addr: str, idx: int) -> str:
    base = titles[idx % len(titles)]
    if KAZAN in addr:
        city = KAZAN
    elif CHELNY in addr:
        city = "\u0427\u0435\u043b\u043d\u044b"
    else:
        city = addr.split(", ")[-1]
    if idx % 4 == 0 and city not in base:
        tpl = TITLE_VARIANTS[idx % len(TITLE_VARIANTS)]
        return tpl.format(city=city)
    return base


def generate_rows(titles: list[str], addresses: list[str], seed: int) -> list[tuple[str, str, str]]:
    rng = random.Random(seed)
    rows: list[tuple[str, str, str]] = []
    used: set[tuple[str, str]] = set()
    for i, addr in enumerate(addresses):
        for attempt in range(20):
            title = pick_title(titles, addr, i + attempt)
            body = body_html(title, i + attempt)
            key = (title, addr)
            if key not in used:
                used.add(key)
                rows.append((title, body, addr))
                break
        else:
            rows.append((pick_title(titles, addr, i), body_html(title, i), addr))
    return rows


def write_csv(path: Path, rows: list[tuple[str, str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, quoting=csv.QUOTE_MINIMAL)
        for h in CSV_HEADER:
            w.writerow(h)
        for row in rows:
            w.writerow(row)


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--export", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--seed", type=int, default=42)
    args = p.parse_args()

    titles = parse_titles(args.export)
    addresses = build_addresses()
    assert len(addresses) == 200, len(addresses)
    rows = generate_rows(titles, addresses, args.seed)
    write_csv(args.output, rows)
    print(f"Wrote {len(rows)} rows to {args.output}")
    print(f"Titles from export: {len(titles)}")
    return 0


